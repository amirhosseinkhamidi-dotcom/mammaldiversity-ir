/* faDigits(x) — عددهای لاتین (0-9) درون یک مقدار را به رقم فارسی (۰-۹) تبدیل
   می‌کند. برای شمارش‌ها، آمار و تاریخ استفاده می‌شود؛ کدها/شناسه‌ها (مثل
   IR0046) و مختصات جغرافیایی/سال‌های استنادی که رفرنس به منابع بین‌المللی‌اند
   عمداً دست‌نخورده می‌مانند. یک فایل مستقل، قبل از سایر اسکریپت‌های هر صفحه
   لود می‌شود. */
(function () {
  "use strict";
  const MAP = { 0: "۰", 1: "۱", 2: "۲", 3: "۳", 4: "۴", 5: "۵", 6: "۶", 7: "۷", 8: "۸", 9: "۹" };
  window.faDigits = function (value) {
    return String(value).replace(/[0-9]/g, (d) => MAP[d]);
  };
})();
